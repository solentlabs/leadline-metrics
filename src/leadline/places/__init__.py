"""The places core knows for every region table: countries, US states, time zones and the region codes.

The data is vendored (countries.json, zones.json and states.json beside this file, regenerated by `make places`
from the standards) and never fetched at run time. A region table's own rules come first and these fill the gaps
(config.load; docs/CONFIGURATION.md, "Shared tables"). Core gives `location` rules (country names, US state names and
abbreviations) and `zones` rules (a time zone's country); a table's `text`, `answer`, `exact`, `models` and `known`
stay its own.

A core rule is a config rule (a region and its lowercase keywords) with a `match` mode, so its keyword is found
as a whole word and not inside another (`in_text`): "oman" is not in "romania", "india" not in "indiana". A rule
a config gives has no mode, and keeps its substring match.
"""

from __future__ import annotations

import json
import pkgutil
import re
from functools import lru_cache
from typing import Any

# The vendored tables (countries.json, zones.json, states.json beside this file), each read the first time it is
# needed: the zones only for a table that reads attached files.
_TABLES: dict[str, dict[str, str]] = {}


def _table(name: str) -> dict[str, str]:
    """The table of `name`.json, read through the package's loader, which reaches it inside leadline.pyz too."""
    if name not in _TABLES:
        raw = pkgutil.get_data(__name__, f"{name}.json")
        if raw is None:  # a loader that cannot read files; none that leadline runs from
            raise RuntimeError(f"leadline's places/{name}.json cannot be read")
        _TABLES[name] = json.loads(raw.decode("utf-8"))["data"]
    return _TABLES[name]


def __getattr__(name: str) -> dict[str, str]:
    """COUNTRIES, ZONES and STATES: ISO code -> English name, zone -> ISO code, USPS code -> state name."""
    if name in ("COUNTRIES", "ZONES", "STATES"):
        return _table(name.lower())
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


# The project's code for Great Britain is the older UK; ISO 3166-1 gives GB. Rows already written use UK.
ALIASES = {"UK": "GB"}
PLACEHOLDER = re.compile(r"X[A-Z]")  # XA to XZ, which ISO 3166-1 leaves for private use; the docs use them as examples
CODE_HELP = "an ISO 3166-1 alpha-2 code, UK for GB, or XA to XZ as a placeholder"

# How a keyword is found in the lowercased text. A rule without `match` is a plain substring (the config's own).
WORD, ZONE, FIELD = "word", "zone", "field"
PATTERNS = {
    WORD: r"(?<!\w){}(?!\w)",
    ZONE: r"(?<![\w/+-]){}(?![\w/+-])",  # a whole zone name, so America/Bahia is not found in America/Bahia_Banderas
    FIELD: r",\s*{}(?:\s*$|\s*[,.;)/|]|\s+\d)",  # ", tx" ending a field of a location: not ", the" or ", in germany"
}

# Names besides the standard's, by ISO code: what people write in a profile.
NAMES = {
    "AE": ["uae"],
    "AS": ["american samoa"],
    "BE": ["belgique"],
    "CD": ["dr congo", "democratic republic of the congo"],
    "CG": ["republic of the congo"],
    "CH": ["schweiz", "suisse", "svizzera"],
    "CI": ["cote d'ivoire", "ivory coast"],
    "CV": ["cabo verde"],
    "CZ": ["czechia"],
    "DE": ["deutschland"],
    "ES": ["españa"],
    "GB": ["united kingdom", "great britain", "britain", "england", "scotland", "wales", "northern ireland", "uk"],
    "IT": ["italia"],
    "KP": ["north korea"],
    "KR": ["south korea"],
    "MK": ["macedonia"],
    "MM": ["burma"],
    "PL": ["polska"],
    "RU": ["russian federation"],
    "SZ": ["swaziland"],
    "TL": ["timor-leste"],
    "TR": ["turkiye", "türkiye"],
    "US": ["usa", "u.s.a", "u.s."],
    "VG": ["british virgin islands"],
    "VI": ["us virgin islands"],
    "WS": ["samoa"],
}

# The US's biggest cities, as the project's configs have always named them.
US_CITIES = (
    "baton rouge", "chicago", "houston", "los angeles", "philadelphia", "phoenix",
    "san antonio", "san diego", "san francisco", "san jose",
)  # fmt: skip

# A country name left out because it is most often the start of a US place: "jersey city, nj" is not Jersey.
LEFT_OUT = frozenset({"jersey"})


def is_code(region: str) -> bool:
    """Whether `region` is a region code: an ISO 3166-1 alpha-2 code, UK, or a placeholder XA to XZ."""
    return region in _table("countries") or region in ALIASES or PLACEHOLDER.fullmatch(region) is not None


def country(region: str) -> str | None:
    """The English name of a region code's country, or None for a placeholder (UK is GB's)."""
    return _table("countries").get(ALIASES.get(region, region))


def canonical(iso: str) -> str:
    """The project's code for a region code: UK for GB, any other code as it is."""
    return next((project for project, standard in ALIASES.items() if standard == iso), iso)


def _name(text: str) -> str:
    return text.lower().replace("&", "and").replace("\N{RIGHT SINGLE QUOTATION MARK}", "'")


@lru_cache(maxsize=None)
def _location_rules() -> tuple[dict[str, Any], ...]:
    names: list[tuple[str, str, int]] = []  # name, region, tie-break: the US before a country of the same name
    names += [(_name(name), "US", 0) for name in _table("states").values()]
    names += [(word, "US", 0) for word in (*NAMES["US"], *US_CITIES)]
    for iso, name in _table("countries").items():
        names.append((_name(name), canonical(iso), 1))
        names += [(_name(word), canonical(iso), 1) for word in NAMES.get(iso, []) if iso != "US"]
    names = [item for item in names if item[0] not in LEFT_OUT]
    names.sort(key=lambda item: (-len(item[0]), item[2], item[0]))
    seen: set[str] = set()
    rules = []
    for name, region, _ in names:
        if name not in seen:  # a name two places share goes to the first (the US, then by length and name)
            seen.add(name)
            rules.append({"region": region, "keywords": [name], "match": WORD})
    # An abbreviation is only a clue after every name has failed: ", de" is Germany as often as Delaware.
    rules += [{"region": "US", "keywords": [code.lower()], "match": FIELD} for code in sorted(_table("states"))]
    return tuple(rules)


@lru_cache(maxsize=None)
def _zone_rules() -> tuple[dict[str, Any], ...]:
    by_region: dict[str, list[str]] = {}
    for zone, iso in _table("zones").items():
        by_region.setdefault(canonical(iso), []).append(zone.lower())
    return tuple(
        {"region": region, "keywords": sorted(zones), "match": ZONE} for region, zones in sorted(by_region.items())
    )


def location_rules() -> list[dict[str, Any]]:
    """The core's `location` rules: names longest first, then the US states' abbreviations."""
    return list(_location_rules())


def zone_rules() -> list[dict[str, Any]]:
    """The core's `zones` rules: one per region, with the lowercase names of its zones."""
    return list(_zone_rules())


@lru_cache(maxsize=None)
def _pattern(keyword: str, match: str) -> re.Pattern[str]:
    return re.compile(PATTERNS[match].format(re.escape(keyword)))


def in_text(keyword: str, match: str | None, lowered: str) -> bool:
    """Whether a rule's `keyword` is in the lowercased text, the way its `match` mode says (None: anywhere)."""
    if keyword not in lowered:
        return False
    return match is None or _pattern(keyword, match).search(lowered) is not None
